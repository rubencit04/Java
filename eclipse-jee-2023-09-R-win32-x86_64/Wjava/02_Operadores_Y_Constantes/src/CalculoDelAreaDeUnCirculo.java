
public class CalculoDelAreaDeUnCirculo {

	public static void main(String[] args) {
		//Formula usada Area = PI *RADIO
		final double PI = 3.14; int radio = 10; double area = PI * (radio * radio);
		System.out.println("Area de estos 2 circulos");
		System.out.println("El area de este circulo es de : "+area);
		System.out.println("-------------------------------------------------------");
		radio = 15; area = PI *(radio * radio);
		System.out.println("El area del segundo circulo es de: "+area);
		
		
	}

}
