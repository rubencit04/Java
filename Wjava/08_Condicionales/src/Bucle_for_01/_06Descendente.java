public class _06Descendente {

	public static void main(String[] args) {
		System.out.println("Numero 10 al 1 descendente");
		System.out.println("------------------------");
		for(int i =10; i >=1;i--){
			System.out.println(i);
			System.out.println("-------------");
			
		}
	}

}
